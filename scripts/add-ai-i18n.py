def merge_into(path, payload):
    data = json.loads(path.read_text(encoding='utf-8'))
    # Insert ai at the alphabetical position (after ads, before analytics).
    # But the file is a dict — order matters only for readability, not for runtime.
    # Insert at end to avoid disturbing existing structure (loader flattens keys anyway).
    if 'ai' in data:
        existing = data['ai']
        # Deep-merge: only set keys not already present (so admin edits survive).
        def deep_merge(target, src):
            for k, v in src.items():
                if k not in target:
                    target[k] = v
                elif isinstance(v, dict) and isinstance(target[k], dict):
                    deep_merge(target[k], v)
        deep_merge(existing, payload)
        data['ai'] = existing
    else:
        data['ai'] = payload
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Updated {path.name}: ai.* keys present')


